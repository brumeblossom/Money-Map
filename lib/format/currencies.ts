export function findCurrency(code: string): CurrencyOption {
  const norm = (code || "NGN").toUpperCase();
  const found = ISO_CURRENCIES.find((c) => c.code === norm);
  if (found) return found;
  return { code: norm, name: norm, symbol: norm };
}
